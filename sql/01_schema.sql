-- Re-runnable: drop the child table first because of the foreign key.
-- (DROP TABLE IF EXISTS also works in SQL Server 2016 and later.)
DROP TABLE IF EXISTS Inspections;
DROP TABLE IF EXISTS Cores;

CREATE TABLE Cores (
    -- T-SQL: Id INT IDENTITY(1,1) PRIMARY KEY
    Id            INT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PartNumber    VARCHAR(50)  NOT NULL,
    DealerId      INT          NOT NULL,   -- ASSUMPTION: no Dealers table was given, so there is no foreign key
    ReceivedDate  DATE         NOT NULL,   -- ASSUMPTION: a date without a time part
    Status        VARCHAR(20)  NOT NULL,   -- ASSUMPTION: same values as the Exercise 1 status enum
    CONSTRAINT CK_Cores_Status
        CHECK (Status IN ('RECEIVED', 'INSPECTED', 'DISASSEMBLED', 'REMANUFACTURED', 'SCRAPPED'))
);

CREATE TABLE Inspections (
    -- T-SQL: Id INT IDENTITY(1,1) PRIMARY KEY
    Id             INT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CoreId         INT          NOT NULL,
    InspectedDate  DATE         NOT NULL,  -- ASSUMPTION: a date without a time part
    Result         VARCHAR(20)  NOT NULL,  -- ASSUMPTION: illustrative values only (the sample data uses PASS / FAIL)
    CONSTRAINT FK_Inspections_Cores FOREIGN KEY (CoreId) REFERENCES Cores (Id)
);

